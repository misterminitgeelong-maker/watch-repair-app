/** Brands containing [query] (case-insensitive), at most [limit]; blank query lists the first [limit]. Empty once [query] exactly matches a brand. */
fun watchBrandSuggestions(query: String, limit: Int = 20, brands: List<String> = WATCH_BRANDS): List<String> {
    val q = query.trim().lowercase()
    if(q.isNotEmpty() && brands.any { it.lowercase() == q }) return emptyList()
    return (if(q.isEmpty()) brands else brands.filter { it.lowercase().contains(q) }).take(limit)
}
